package code.name.monkey.retromusic.util

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import code.name.monkey.retromusic.R
import code.name.monkey.retromusic.model.Song
import code.name.monkey.retromusic.util.MergedImageUtils.joinImages
import code.name.monkey.retromusic.util.MusicUtil.getMediaStoreAlbumCoverUri
import com.bumptech.glide.Glide
import com.bumptech.glide.load.resource.bitmap.RoundedCorners

object AutoGeneratedPlaylistBitmap {
    fun getBitmap(
        context: Context, songPlaylist: List<Song>?
    ): Bitmap? {
        if (songPlaylist.isNullOrEmpty()) return getDefaultBitmap(context)
        val validSongs = songPlaylist.filter { !MusicUtil.isAlbumNameUnknown(it.albumName, it.artistName) }
        if (validSongs.isEmpty()) return getDefaultBitmap(context)
        if (validSongs.size == 1) return getBitmapWithSong(context, validSongs[0])
        val songsByAlbum = validSongs.distinctBy { it.albumId }
        val art: MutableList<Bitmap> = ArrayList()
        for (song in songsByAlbum) {
            val bitmap = getBitmapWithSong(context, song)
            if (bitmap != null) art.add(bitmap)
            if (art.size == 9) break
        }
        return if (art.isEmpty()) getDefaultBitmap(context) else joinImages(art)
    }

    private fun getBitmapWithSong(context: Context, song: Song): Bitmap? {
        return try {
            Glide.with(context)
                .asBitmap()
                .transform(RoundedCorners(20))
                .load(code.name.monkey.retromusic.glide.RetroGlideExtension.getSongModel(song))
                .submit(200, 200)
                .get()
        } catch (e: Exception) {
            null
        }
    }

    private fun getDefaultBitmap(context: Context): Bitmap {
        return BitmapFactory.decodeResource(context.resources, R.drawable.default_album_art)
    }
}